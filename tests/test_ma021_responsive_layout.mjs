assert.ok(manager.detailLayoutProfile({width:320,height:480}).width<=320);
assert.match(file,/@media\(min-width:680px\) and \(max-width:1179px\)/);
assert.match(file,/@media\(max-width:679px\)/);
assert.match(file,/@media\(max-height:500px\)/);
assert.match(file,/gr-ma-detail-intro/);
assert.match(file,/gr-ma-detail-grid-wrap/);
assert.match(file,/grid-template-columns:repeat\(2,minmax\(0,1fr\)\)/);
assert.match(file,/clampDetailPosition\(pos,viewport\)/);
assert.match(file,/globalThis\.visualViewport\?\.addEventListener\?\.\('resize'/);
