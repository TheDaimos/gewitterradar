// V4.14.20: existing weather GeoPoint Inspector is reused by MA-021 location details.
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const root=new URL('../',import.meta.url);
const manager=readFileSync(new URL('frontend/modules/monitored-areas/location-manager.js',root),'utf8');
const controls=readFileSync(new URL('frontend/modules/ui/controls.js',root),'utf8');
const temperature=readFileSync(new URL('frontend/modules/weather/temperature-display.js',root),'utf8');
assert.match(manager,/detailGeo:'GeoPoint'/);
assert.match(manager,/detailGeo:'GeoPoint'/);
assert.match(manager,/typeof openGeoPoint==='function'/);
assert.ok(manager.includes('content.append(shortcuts);'),'GeoPoint button must be visible above the collapsed details');
assert.match(manager,/await openGeoPoint\(\{latitude:data\.latitude,longitude:data\.longitude\}\)/);
assert.match(manager,/geoButton\.disabled=true/);
const start=manager.indexOf("const shortcuts=node('div','', 'gr-ma-detail-shortcuts')");
const end=manager.indexOf("const accordion=document.createElement('details')",start);
const action=manager.slice(start,end);
assert.ok(start>0&&end>start,'button must exist');
assert.ok(action.indexOf('await openGeoPoint')<action.indexOf('close();'),'close only after provider ACK');
assert.match(action,/catch\{message\.textContent=t\.detailGeoError;\}/);
assert.doesNotMatch(action,/focus\(|flyTo\(|setLocation\(|selectReference/);
assert.match(controls,/openGeoPoint:async position=>/);
assert.match(controls,/this\._weatherTemperatureOpenGeoPointAt/);
assert.match(controls,/if\(!sameProfile\(\)\)throw new Error\('MA_PROFILE_CHANGED'\)/);
assert.match(temperature,/async _weatherTemperatureOpenGeoPointAt\(\{latitude,longitude\}=\{\}\)/);
const startWeather=temperature.indexOf('async _weatherTemperatureOpenGeoPointAt(');
const endWeather=temperature.indexOf('async _weatherTemperatureInspect(',startWeather);
const bridge=temperature.slice(startWeather,endWeather);
assert.match(bridge,/this\._resumeWeatherTemperature\(\)/);
assert.match(bridge,/await this\._weatherTemperatureInspect\(\{lat:latitude,lng:longitude\}\)/);
assert.match(bridge,/this\.shadow\.getElementById\('weather-temperature-point'\)/);
assert.match(bridge,/return \{opened:true,latitude,longitude\}/);
assert.match(bridge,/MA_GEOPOINT_INVALID_COORDINATES/);
assert.doesNotMatch(bridge,/flyTo\(|panTo\(|setView\(|selectReference|_locationSelectEntity|_weatherTemperatureSet\(/);
assert.match(temperature,/GeoPointAdapters/);
assert.match(temperature,/GeoPoint Inspector/);
assert.match(temperature,/no_authorized_field/);
console.log('PASS MA-021 existing GeoPoint launch, correct coordinates, explicit success, no tracker shift');
