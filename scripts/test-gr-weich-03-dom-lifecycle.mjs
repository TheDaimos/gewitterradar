import assert from "node:assert/strict";
import {installWeatherDisplayMenu} from "../frontend/modules/weather/display-menu.js";
import {installRasterLab} from "../frontend/modules/diagnostics/raster-lab.js";
import {APPLICATION_RELEASE} from "../frontend/version.js";
const Card=class {};
installWeatherDisplayMenu(Card,{});
installRasterLab(Card,{});
const card=new Card();
const pane={style:{filter:"",opacity:"",willChange:"",imageRendering:"",setProperty() {},removeProperty(key){this[key]="";}},dataset:{},querySelectorAll(){return [];},getRootNode(){return null;}};
const mapListeners=new Map();
let zoom=8;
card._map={getZoom(){return zoom;},getPane(name){return name==="gr-weather-radar"?pane:null;},on(name,handler){mapListeners.set(name,handler);},off(name){mapListeners.delete(name);}};
let active={options:{maxNativeZoom:18}};
card._weatherRadarState=()=>({layer:active});
card.__weatherDisplayState={config:{styles:{precipitation:"soft"},opacities:{precipitation:null}},zoomMap:null,zoomHandler:null};
card._weatherDisplayState=()=>card.__weatherDisplayState;
card._weatherDisplayStyle=()=>card.__weatherDisplayState.config.styles.precipitation;
card._weatherDisplaySyncLegendBadge=()=>{};
for(const mode of ["precise","balanced","soft","auto"]){
 card.__weatherDisplayState.config.styles.precipitation=mode;
 card._weatherDisplayRefreshRenderedLayers();
 assert.equal(pane.dataset.weatherDisplayStyle,mode);
 assert.match(pane.style.filter,mode==="precise"?/^none$/:/^(?:blur\(|url\()/);
 if(mode==="soft")assert.ok(card._weatherDisplayRasterTuning("precipitation").blur>card._weatherDisplayRasterTuning("precipitation").blur*0.5);
}
card.__weatherDisplayState.config.styles.precipitation="balanced";
card._weatherDisplayEnsureZoomSync();
assert.ok(mapListeners.has("zoomend"));
zoom=10;mapListeners.get("zoomend")();
assert.equal(pane.dataset.weatherDisplayStyle,"balanced");
const atTen=card._weatherDisplayRasterTuning("precipitation").blur;
assert.ok(atTen>0);
active={options:{maxNativeZoom:10}}; // simulate V1 after V2; URL ceiling must not change visual reference
card._weatherDisplayRefreshRenderedLayers();
assert.equal(card._weatherDisplayRasterTuning("precipitation").blur,atTen);
card.__weatherDisplayState.config.styles.precipitation="soft";
card._weatherDisplayRefreshRenderedLayers();
const original=pane.style.filter;
const lab=card._rasterLabState();
lab.open=true;lab.preview=true;
const info=card._rasterLabSnapshot();
lab.samples.set(card._rasterLabKey(info),{layer:"precipitation",zoom:10,nativeZoom:10,values:{...info.base,blur:30,blend:100,opacity:.6}});
card._rasterLabReapplyPreview();
assert.equal(pane.dataset.rasterLabPreview,"true");
assert.match(pane.style.filter,/blur\(30\.00px\)/);
lab.preview=false;
card._rasterLabRestore();
assert.equal(pane.dataset.rasterLabPreview,undefined);
assert.equal(pane.style.filter,original);
lab.open=false;
const exportInfo=card._rasterLabExport();
assert.equal(exportInfo.version,APPLICATION_RELEASE.version);
assert.equal(exportInfo.runtimeRevision,APPLICATION_RELEASE.runtimeRevision);
console.log("PASS GR-WEICH-03 DOM logic: four modes, zoom, V1/V2 ceilings, lab preview and restoration; NOT browser pixel parity");
