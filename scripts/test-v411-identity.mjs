import assert from 'node:assert/strict';
import {readFile,readdir} from 'node:fs/promises';
import {resolve} from 'node:path';
import {root,hash} from './build-frontend.mjs';
const read=async path=>readFile(resolve(root,path),'utf8');
const entry=await read('frontend/gewitterradar.js');
const manifest=await read('frontend/module-manifest.js');
const runtime=JSON.parse(await read('frontend/assets/gewitterradar-runtime-manifest.json'));
const inventory=JSON.parse(await read('frontend/assets.json'));
const build=await read('custom_components/gewitterradar/build_info.py');
const expected='V4.11.01-DEV-2026-09-30';
assert.match(entry,/const GEWITTERRADAR_FEATURE_CACHE = '41101r1';/);
assert.match(entry,/CARD_VERSION=APPLICATION_META.version;/);
assert.match(entry,/CARD_DISPLAY_VERSION=APPLICATION_META.displayVersion.replace\(\/\^V\/,' '\);|CARD_DISPLAY_VERSION=APPLICATION_META.displayVersion.replace\(\/\^V\/,''\);/);
assert.match(manifest,/version:"4.11.01",displayVersion:"V4.11.01 DEV",build:"V4.11.01-DEV-2026-09-30"/);
assert.equal(runtime.productVersion,'4.11.01');assert.equal(runtime.build,expected);
assert.equal(runtime.moduleSetId,'E411-01A1');
assert.equal(runtime.modules.filter(x=>x.id==='weather.consumer-client').length,1);
assert.equal(build.includes('BUILD_VERSION = "4.11.01"'),true);
assert.equal(inventory.find(x=>x.file==='assets/gewitterradar-runtime-manifest.json').sha256,hash(await readFile(resolve(root,'frontend/assets/gewitterradar-runtime-manifest.json'))));
const m=await read('frontend/modules/weather/consumer-client.js');
assert.match(m,/id:'weather.consumer-client',version:'1.0.1'/);
assert.match(entry,/installWeatherRouter\(GewitterradarCard,__moduleDeps\)/);
assert.ok(!entry.includes("const CARD_VERSION = '4.10';"));
console.log('PASS: V4.11.01 DEV identity synchronized in UI entry, module manifest, runtime manifest, asset checksums and DRA build info.');
